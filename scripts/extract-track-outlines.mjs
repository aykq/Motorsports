function mapUrl(name) {
  return `https://media.formula1.com/image/upload/c_lfill,w_3392/q_auto/v1740000001/content/dam/fom-website/2018-redesign-assets/Circuit%20maps%2016x9/${name}.webp`;
}

// path "d" string'inden yaklaşık bounding-box köşegenini hesapla (M/L komutlarındaki koordinatlar)
function pathDiagonal(d) {
  const nums = d.match(/-?\d+(\.\d+)?/g)?.map(Number) ?? [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (let i = 0; i < nums.length - 1; i += 2) {
    const x = nums[i];
    const y = nums[i + 1];
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return Math.hypot(maxX - minX, maxY - minY);
}

async function extractOne(circuitId, fileName) {
  const res = await fetch(mapUrl(fileName));
  if (!res.ok) throw new Error(`fetch failed for ${circuitId}: ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());

  const { data, info } = await sharp(buf)
    .resize(600, null, { withoutEnlargement: true })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const imgData = { width: info.width, height: info.height, data: new Uint8ClampedArray(data) };
  const svgString = ImageTracer.imagedataToSVG(imgData, { ltres: 1, qtres: 1, pathomit: 8, numberofcolors: 4 });

  const pathMatches = [...svgString.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (pathMatches.length === 0) throw new Error(`no paths extracted for ${circuitId}`);

  const diagonal = Math.hypot(info.width, info.height);
  const threshold = diagonal * 0.25;
  const candidates = pathMatches
    .map((d) => ({ d, size: pathDiagonal(d) }))
    .filter((p) => p.size >= threshold)
    .sort((a, b) => b.size - a.size);

  if (candidates.length === 0) throw new Error(`no path passed size threshold for ${circuitId} — needs manual trace`);

  return { viewBox: `0 0 ${info.width} ${info.height}`, path: candidates[0].d };
}

async function main() {
  const results = {};
  const failures = [];
  for (const [circuitId, fileName] of Object.entries(CIRCUITS)) {
    try {
      results[circuitId] = await extractOne(circuitId, fileName);
      console.log(`OK ${circuitId}`);
    } catch (err) {
      failures.push(circuitId);
      console.error(`FAIL ${circuitId}: ${err.message}`);
    }
  }

  const header = "// AUTO-GENERATED by scripts/extract-track-outlines.mjs — do not hand-edit, re-run script instead.\n";
  const body = `export interface TrackOutline {\n  viewBox: string;\n  path: string;\n}\n\nexport const TRACK_OUTLINES: Record<string, TrackOutline> = ${JSON.stringify(results, null, 2)};\n`;
  await fs.writeFile("src/lib/track-outlines.generated.ts", header + body);

  console.log(`\n${Object.keys(results).length}/${Object.keys(CIRCUITS).length} circuits extracted.`);
  if (failures.length > 0) {
    console.log(`Manual trace needed for: ${failures.join(", ")}`);
  }
}

main();
